function sheet(aoa, cols) {
  const ws = XLSX.utils.aoa_to_sheet(aoa);
  if (cols) ws["!cols"] = cols.map((wch) => ({ wch }));
  return ws;
}

function setFormula(ws, addr, formula) {
  ws[addr] = { t: "n", f: formula, v: 0 };
  const range = XLSX.utils.decode_range(ws["!ref"] || "A1:A1");
  const cell = XLSX.utils.decode_cell(addr);
  if (cell.r > range.e.r) range.e.r = cell.r;
  if (cell.c > range.e.c) range.e.c = cell.c;
  ws["!ref"] = XLSX.utils.encode_range(range);
}

function querySheet(formula) {
  return {
    A1: { t: "n", f: formula, v: 0 },
    "!ref": "A1",
    "!cols": [{ wch: 16 }, { wch: 40 }, { wch: 16 }, { wch: 18 }, { wch: 14 }],
  };
}

